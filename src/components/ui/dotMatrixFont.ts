/** Every lit cell of a character, as [column, row] pairs. */
export function glyphCells(character: string): [number, number][] {
    const rows = GLYPHS[character.toUpperCase()] ?? GLYPHS[' '];
    const cells: [number, number][] = [];

    rows.forEach((row, rowIndex) => {
        row.split('').forEach((cell, columnIndex) => {
            if (cell === '1') {
                cells.push([columnIndex, rowIndex]);
            }
        });
    });

    return cells;
}
