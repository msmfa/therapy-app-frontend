// 🔑 Principles from neuroplasticity research

// Consolidation window

// After therapy (or any emotionally significant experience), the brain goes through early consolidation (hours) and systems consolidation (days).

// Revisiting the insight within the same day (6–12h) and the next morning (post-sleep) strengthens the trace.

// Repeated, spaced activation

// New pathways need multiple reactivations over days to become stable.

// If sessions are far apart, you need more reminders in between.

// If sessions are close together, reminders should focus on prepping for the next session rather than flooding.

// Emotional salience matters

// A reminder that reactivates the felt state (not just the words) engages the same circuits as in-session learning.

// Timing reminders during moments of likely relevance (e.g., evening reflection, morning priming) matters more than raw spacing.

// Synaptic tagging and capture

// Brain tags recent patterns as “important.” If reactivated within hours to days, they’re more likely to consolidate into long-term pathways.

// If not, the tag decays and the pattern is lost.

// 🧠 Algorithm outline (not memory-based, but plasticity-based)

// For each gap between sessions:

// Immediately after a session

// Same-day “integration reminder” at reflection time (evening).

// Purpose: reinforce what was emotionally significant while tags are fresh.

// Next morning

// “Post-sleep priming reminder.”

// Purpose: reactivate pattern after the brain’s overnight consolidation.

// Mid-gap reinforcement

// 1–2 reactivations spaced evenly through the gap (depends on gap length).

// For a 2-day gap → none.

// For a 5-day gap → one at ~day 3.

// For a 7–10 day gap → one at ~day 3 and ~day 6.

// Longer gaps → repeat every 3–5 days.

// Pre-session reminder

// The day before (or morning of) the next session.

// Purpose: reactivate circuits and prepare for therapy to build on.
